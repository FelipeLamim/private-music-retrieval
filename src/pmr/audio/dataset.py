def _convert(src: Path, target_sr: int) -> tuple:
    """Decode a WAV file and convert it to mono/target_sr/int16; returns (pcm, modifications, fmt)."""
    fmt = read_wav_format(src)
    if fmt.num_frames == 0:
        raise ValueError(f"{src}: WAV file contains no audio samples")
    seconds = fmt.num_frames / fmt.sample_rate
    if seconds > MAX_IMPORT_SECONDS:
        raise ValueError(f"{src}: {seconds:.0f} s is longer than the {MAX_IMPORT_SECONDS:.0f} s import limit")
    if fmt.num_frames * fmt.channels > MAX_IMPORT_SAMPLES:
        raise ValueError(f"{src}: {fmt.num_frames * fmt.channels} samples exceed the import limit of "
                         f"{MAX_IMPORT_SAMPLES}; shorten or downmix the file first")
    if fmt.encoding == "s16" and fmt.valid_bits == 16 and fmt.channels == 1 and fmt.sample_rate == target_sr:
        return read_wav_pcm16_mono(src).pcm, [], fmt  # already in catalog format: copied unchanged
    mods = []
    fmt, x = read_wav_float(src)
    if fmt.encoding != "s16":
        mods.append(f"converted sample format from {fmt.describe()} to 16-bit signed integer PCM")
    if fmt.channels > 1:
        x = x.sum(axis=1) / fmt.channels
        mods.append(f"downmixed {fmt.channels} channels to mono (arithmetic mean of the channels)")
    else:
        x = x[:, 0]
    if fmt.sample_rate != target_sr:
        from scipy.signal import resample_poly

        g = math.gcd(fmt.sample_rate, target_sr)
        up, down = target_sr // g, fmt.sample_rate // g
        x = resample_poly(x, up, down)
        mods.append(
            f"resampled from {fmt.sample_rate} Hz to {target_sr} Hz with scipy.signal.resample_poly "
            f"(up={up}, down={down}, Kaiser window beta=5.0)"
        )
    samples, clipped = float_to_pcm16(x)
    mods.append(f"rounded to the nearest 16-bit integer (half to even, no dither) and clipped to "
                f"[-32768, 32767]; {clipped} samples clipped")
    return array_to_pcm16(samples), mods, fmt


def _attribution_markdown(manifest: dict) -> str:
    lines = [
        f"# Attribution: catalog `{manifest['catalog_id']}`",
        "",
        "Tracks below were imported from third parties or supplied by the user. Each entry gives title,",
        "creator, source, license and the modifications made by `pmr.audio.dataset import`",
        "(TASL: Title, Author, Source, License). Synthetic tracks (origin `synthetic`) are CC0-1.0",
        "and are not listed. The license of every imported track was confirmed by the importer;",
        "re-check the source page before redistributing.",
        "",
    ]
    for t in manifest["tracks"]:
        if t["origin"] == "synthetic":
            continue
        lines += [
            f"## `{t['id']}`: {t['title']}",
            "",
            f"- Creator: {t['artist']}",
            f"- Origin: {t['origin']}",
            f"- Source: {t['source_url'] or 'not published (user recording)'}",
            f"- License: {t['license']} ({t['license_url']})",
            f"- Attribution: {t['attribution'] or '(none required)'}",
            "- Modifications: " + ("; ".join(t["modifications"]) if t["modifications"] else "none (copied unchanged)"),
        ]
        if t.get("notes"):
            lines.append(f"- Notes: {t['notes']}")
        lines.append("")
    return "\n".join(lines)


def _next_id(tracks: list, index: int) -> str:
    ids = {t["id"] for t in tracks}
    candidate, k = f"t{index:02d}", 1
    while candidate in ids:
        candidate = f"t{index:02d}_{k}"
        k += 1
    return candidate


def import_track(catalog_dir: PathLike, src_wav: PathLike, *, title: str, artist: str, license: str,
                 source_url: Optional[str], license_url: Optional[str], attribution: Optional[str],
                 confirm_license_verified: bool, notes: Optional[str] = None,
                 origin: str = "third_party") -> dict:
    """Add a CC0/CC BY (or user's own) WAV recording to a catalog; returns the new track entry.

    The audio is converted to mono, 16 kHz, signed 16-bit and every change is recorded in
    ``modifications``. The track gets the next PIR index; ``ATTRIBUTION.md`` is rewritten.
    A missing catalog directory/manifest is created as a new catalog.
    """
    if confirm_license_verified is not True:
        raise ValueError(
            "refusing to import: confirm that you checked the license on the source page and that it "
            "allows redistribution and modification (confirm_license_verified=True, CLI "
            "--confirm-license-verified). A free download does not imply permission to redistribute."
        )
    if origin not in IMPORT_ORIGINS:
        raise ValueError(f"origin must be one of {IMPORT_ORIGINS} (synthetic tracks come from 'generate')")
    lic = normalize_license(license)
    title = _clean_text("title", title, required=True, max_len=200)
    artist = _clean_text("artist", artist, required=True, max_len=200)
    is_by = lic.startswith("CC-BY")
    attribution = _clean_text("attribution", attribution, required=is_by, max_len=1000)
    if is_by and attribution is None:  # pragma: no cover - _clean_text raised already
        raise ValueError("CC BY tracks require an attribution")
    notes = _clean_text("notes", notes, required=False, max_len=2000)
    source_url = _clean_text("source_url", source_url, required=False, max_len=2000)
    if source_url is None and (is_by or origin == "third_party"):
        raise ValueError("source_url is required for CC BY tracks and for third-party recordings")
    if source_url is not None and not _is_http_url(source_url):
        raise ValueError(f"source_url {source_url!r} must be an http(s) URL")
    license_url = _clean_text("license_url", license_url, required=False, max_len=2000) or ALLOWED_LICENSES[lic]
    if not _is_http_url(license_url):
        raise ValueError(f"license_url {license_url!r} must be an http(s) URL")
    if not _license_url_matches(lic, license_url):
        raise ValueError(f"license_url {license_url!r} does not match license {lic} ({ALLOWED_LICENSES[lic]})")

    src = Path(src_wav)
    if not src.is_file():
        raise ValueError(f"{src}: source file not found")
    with open(src, "rb") as fh:
        head = fh.read(16)
    kind = sniff_audio_container(head)
    convert_hint = (
        "convert it to WAV first, e.g. on a machine with ffmpeg: "
        "ffmpeg -i input -ac 1 -ar 16000 -c:a pcm_s16le output.wav "
        "(ffmpeg is not available in this environment)"
    )
    if kind != "WAV":
        raise ValueError(f"{src}: not a WAV file (detected: {kind}); {convert_hint}")
    try:
        pcm, mods, fmt = _convert(src, CATALOG_SAMPLE_RATE)
    except ValueError as exc:
        if "unsupported" in str(exc):
            raise ValueError(f"{exc}; {convert_hint}") from None
        raise
    source_hash = hashlib.sha256()
    with open(src, "rb") as fh:
        for block in iter(lambda: fh.read(1 << 20), b""):
            source_hash.update(block)
    source_sha = source_hash.hexdigest()

    root = Path(catalog_dir)
    with _catalog_lock(root):
        if (root / MANIFEST).exists():
            manifest = load_manifest(root)
            if manifest["sample_rate"] != CATALOG_SAMPLE_RATE:
                raise ValueError(f"catalog sample rate {manifest['sample_rate']} != {CATALOG_SAMPLE_RATE}")
        else:
            cid = re.sub(r"[^A-Za-z0-9._-]", "-", root.resolve().name) or "catalog"
            manifest = {"schema_version": SCHEMA_VERSION, "catalog_id": f"user-{cid}", "created_by": CREATED_BY,
                        "sample_rate": CATALOG_SAMPLE_RATE, "channels": 1, "sample_width": 2, "tracks": []}
        digest = sha256_hex(pcm)
        for t in manifest["tracks"]:
            if t["sha256_pcm"] == digest:
                raise ValueError(f"{src}: identical audio is already in the catalog as {t['id']}")
        tracks = manifest["tracks"]
        index = len(tracks)
        tid = _next_id(tracks, index)
        n = len(pcm) // 2
        entry = {
            "id": tid,
            "index": index,
            "title": title,
            "artist": artist,
            "duration_s": n / CATALOG_SAMPLE_RATE,
            "num_samples": n,
            "pcm_bytes": len(pcm),
            "sha256_pcm": digest,
            "file": f"tracks/{tid}.wav",
            "origin": origin,
            "license": lic,
            "license_url": license_url,
            "attribution": attribution or "",
            "source_url": source_url,
            "modifications": mods,
            "generator": None,
            "notes": notes,
            "source_file": src.name,
            "source_sha256": source_sha,
            "source_format": f"{fmt.describe()}, {fmt.channels} channel(s), {fmt.sample_rate} Hz",
        }
        new_manifest = dict(manifest, tracks=tracks + [entry])
        problems = validate_manifest(new_manifest)
        if problems:
            raise ValueError("import would produce an invalid manifest: " + "; ".join(problems))
        (root / "tracks").mkdir(parents=True, exist_ok=True)
        write_wav(root / entry["file"], pcm, CATALOG_SAMPLE_RATE)
        atomic_write_bytes(root / ATTRIBUTION, (_attribution_markdown(new_manifest).encode("utf-8"),))
        _write_manifest(root, new_manifest)
    return entry


