"""Audio catalogs: generation, manifest validation, verification and user/CC import.

Layout of a catalog directory::

    <dir>/manifest.json        schema_version 1, UTF-8, sorted keys
    <dir>/tracks/<id>.wav      16 kHz mono signed 16-bit PCM, canonical 44-byte header
    <dir>/ATTRIBUTION.md       only when the catalog contains non-synthetic tracks

Track ``index`` (0-based position in ``tracks``) is the PIR record index.
Command line: ``python -m pmr.audio.dataset {generate,verify,import,info} ...``.
"""
