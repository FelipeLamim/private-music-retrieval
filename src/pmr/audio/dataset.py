def _peak_rss_mib() -> float:
    return resource.getrusage(resource.RUSAGE_SELF).ru_maxrss / 1024.0  # KiB on Linux


def _cmd_generate(args) -> int:
    t0 = time.perf_counter()

    def progress(i, n, spec, seconds):
        print(f"[{i + 1:>3}/{n}] {spec.id} {spec.duration_s:7.2f} s  {spec.meter:>4} {spec.tempo_bpm:5.1f} BPM "
              f"{spec.key:>2} {spec.mode:<14} render+write {seconds:6.2f} s", flush=True)

    manifest = generate_catalog(args.out, profile=args.profile, n_tracks=args.n_tracks,
                                duration_s=args.duration_s, base_seed=args.seed, progress=progress)
    total_s = sum(t["duration_s"] for t in manifest["tracks"])
    total_b = sum(t["pcm_bytes"] for t in manifest["tracks"])
    print(f"catalog {manifest['catalog_id']}: {len(manifest['tracks'])} tracks, {total_s:.2f} s audio, "
          f"{total_b} PCM bytes; wall time {time.perf_counter() - t0:.2f} s; peak RSS {_peak_rss_mib():.0f} MiB")
    return 0


def _cmd_verify(args) -> int:
    t0 = time.perf_counter()
    problems = verify_catalog(args.dir, rerender=args.rerender)
    for p in problems:
        print(f"PROBLEM: {p}")
    status = "OK" if not problems else f"{len(problems)} problem(s)"
    print(f"verify {args.dir}: {status} ({'with' if args.rerender else 'without'} re-render, "
          f"{time.perf_counter() - t0:.2f} s)")
    return 0 if not problems else 1


def _cmd_import(args) -> int:
    entry = import_track(args.dir, args.src, title=args.title, artist=args.artist, license=args.license,
                         source_url=args.source_url, license_url=args.license_url, attribution=args.attribution,
                         confirm_license_verified=args.confirm_license_verified, notes=args.notes,
                         origin=args.origin)
    print(f"imported {entry['id']} (index {entry['index']}): {entry['duration_s']:.2f} s, {entry['pcm_bytes']} bytes")
    for m in entry["modifications"] or ["no modifications (already 16 kHz mono 16-bit)"]:
        print(f"  - {m}")
    return 0


def _cmd_info(args) -> int:
    manifest = load_manifest(args.dir)
    if args.json:
        print(manifest_json(manifest), end="")
        return 0
    tracks = manifest["tracks"]
    total_s = sum(t["duration_s"] for t in tracks)
    total_b = sum(t["pcm_bytes"] for t in tracks)
    print(f"catalog_id   {manifest['catalog_id']}")
    print(f"created_by   {manifest['created_by']}")
    print(f"format       {manifest['sample_rate']} Hz, mono, signed 16-bit")
    print(f"tracks       {len(tracks)}; {total_s:.2f} s total; {total_b} PCM bytes; "
          f"min/max {min(t['pcm_bytes'] for t in tracks)}/{max(t['pcm_bytes'] for t in tracks)} bytes")
    for t in tracks:
        gen = t["generator"] or {}
        desc = f"{gen.get('meter', '')} {gen.get('tempo_bpm', '')} {gen.get('key', '')} {gen.get('mode', '')}".strip()
        print(f"  {t['index']:>3} {t['id']:<6} {t['duration_s']:8.2f} s {t['pcm_bytes']:>9} B "
              f"{t['origin']:<11} {t['license']:<9} {t['title']} ({t['artist']}) {desc}")
    return 0


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(prog="python -m pmr.audio.dataset", description=__doc__.split("\n")[0])
    sub = p.add_subparsers(dest="command", required=True)
    g = sub.add_parser("generate", help="render a synthetic catalog")
    g.add_argument("--profile", choices=sorted(PROFILES), default="full")
    g.add_argument("--out", required=True, help="catalog directory")
    g.add_argument("--n-tracks", type=int, default=None)
    g.add_argument("--duration-s", type=float, default=None, help="same duration for every track")
    g.add_argument("--seed", type=int, default=synth.DEFAULT_BASE_SEED, help="base seed")
    g.set_defaults(func=_cmd_generate)
    v = sub.add_parser("verify", help="check manifest, files and hashes")
    v.add_argument("dir")
    v.add_argument("--rerender", action="store_true", help="also re-render every synthetic track")
    v.set_defaults(func=_cmd_verify)
    i = sub.add_parser("import", help="add a CC0/CC BY or own WAV recording")
    i.add_argument("dir")
    i.add_argument("--src", required=True, help="input WAV file")
    i.add_argument("--title", required=True)
    i.add_argument("--artist", required=True, help="creator name")
    i.add_argument("--license", required=True, help=f"one of {', '.join(ALLOWED_LICENSES)}")
    i.add_argument("--source-url", default=None)
    i.add_argument("--license-url", default=None)
    i.add_argument("--attribution", default=None)
    i.add_argument("--confirm-license-verified", action="store_true")
    i.add_argument("--origin", choices=IMPORT_ORIGINS, default="third_party")
    i.add_argument("--notes", default=None)
    i.set_defaults(func=_cmd_import)
    n = sub.add_parser("info", help="print a catalog summary")
    n.add_argument("dir")
    n.add_argument("--json", action="store_true")
    n.set_defaults(func=_cmd_info)
    return p


def main(argv=None) -> int:
    args = build_parser().parse_args(argv)
    try:
        return args.func(args)
    except ValueError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
