def validate_manifest(manifest, catalog_dir: Optional[Path] = None) -> list:
    """Return a list of schema problems (empty when the manifest is valid)."""
    problems = []
    if not isinstance(manifest, dict):
        return ["manifest must be a JSON object"]
    for key, typ in REQUIRED_TOP.items():
        if key not in manifest:
            problems.append(f"missing top-level key {key!r}")
        elif not isinstance(manifest[key], typ) or isinstance(manifest[key], bool):
            problems.append(f"top-level {key!r} must be of type {typ.__name__}")
    if problems:
        return problems
    if manifest["schema_version"] != SCHEMA_VERSION:
        problems.append(f"unsupported schema_version {manifest['schema_version']} (expected {SCHEMA_VERSION})")
    if not _CATALOG_ID_RE.match(manifest["catalog_id"]):
        problems.append(f"invalid catalog_id {manifest['catalog_id']!r}")
    if not manifest["created_by"].strip():
        problems.append("created_by must not be empty")
    sr = manifest["sample_rate"]
    if not 8000 <= sr <= 96000:
        return problems + [f"sample_rate {sr} out of range [8000, 96000]"]
    if manifest["channels"] != 1:
        problems.append("channels must be 1 (mono)")
    if manifest["sample_width"] != 2:
        problems.append("sample_width must be 2 (signed 16-bit)")
    tracks = manifest["tracks"]
    if not tracks:
        problems.append("tracks must not be empty")
    seen_ids, seen_files = set(), set()
    for pos, t in enumerate(tracks):
        where = f"tracks[{pos}]"
        if not isinstance(t, dict):
            problems.append(f"{where} must be an object")
            continue
        missing = [k for k in REQUIRED_TRACK if k not in t]
        if missing:
            problems.append(f"{where} missing keys {missing}")
            continue
        tid = t["id"]
        if not isinstance(tid, str) or not _ID_RE.match(tid):
            problems.append(f"{where}: invalid id {tid!r}")
        elif tid in seen_ids:
            problems.append(f"{where}: duplicate id {tid!r}")
        else:
            seen_ids.add(tid)
            where = f"track {tid}"
        if not isinstance(t["index"], int) or isinstance(t["index"], bool) or t["index"] != pos:
            problems.append(f"{where}: index {t['index']!r} must equal its position {pos}")
        for key in ("title", "artist"):
            if not isinstance(t[key], str) or not t[key].strip():
                problems.append(f"{where}: {key} must be a non-empty string")
        n = t["num_samples"]
        if not isinstance(n, int) or isinstance(n, bool) or n <= 0:
            problems.append(f"{where}: num_samples must be a positive integer")
            n = None
        if not isinstance(t["pcm_bytes"], int) or isinstance(t["pcm_bytes"], bool):
            problems.append(f"{where}: pcm_bytes must be an integer")
        elif n is not None and t["pcm_bytes"] != 2 * n:
            problems.append(f"{where}: pcm_bytes {t['pcm_bytes']} != 2 * num_samples ({2 * n})")
        d = t["duration_s"]
        if not isinstance(d, (int, float)) or isinstance(d, bool) or not math.isfinite(d):
            problems.append(f"{where}: duration_s must be a number")
        elif n is not None and abs(d - n / sr) > 1e-3:
            problems.append(f"{where}: duration_s {d} != num_samples / sample_rate ({n / sr})")
        if not isinstance(t["sha256_pcm"], str) or not _SHA_RE.match(t["sha256_pcm"]):
            problems.append(f"{where}: sha256_pcm must be 64 lowercase hex digits")
        f = t["file"]
        if not isinstance(f, str) or "\\" in f or f.startswith("/") or not f.startswith("tracks/") \
                or not f.endswith(".wav") or any(part in ("", ".", "..") for part in f.split("/")):
            problems.append(f"{where}: file {f!r} must be a relative path tracks/<name>.wav inside the catalog")
        elif f in seen_files:
            problems.append(f"{where}: file {f!r} listed twice")
        else:
            seen_files.add(f)
        origin = t["origin"]
        if origin not in ORIGINS:
            problems.append(f"{where}: origin {origin!r} must be one of {ORIGINS}")
        lic = t["license"]
        if lic not in ALLOWED_LICENSES:
            problems.append(f"{where}: license {lic!r} not in {sorted(ALLOWED_LICENSES)}")
        if not _is_http_url(t["license_url"]):
            problems.append(f"{where}: license_url must be an http(s) URL")
        elif lic in ALLOWED_LICENSES and not _license_url_matches(lic, t["license_url"]):
            problems.append(f"{where}: license_url does not match license {lic}")
        if not isinstance(t["attribution"], str):
            problems.append(f"{where}: attribution must be a string")
        elif isinstance(lic, str) and lic.startswith("CC-BY") and not t["attribution"].strip():
            problems.append(f"{where}: CC BY tracks need a non-empty attribution")
        src = t["source_url"]
        if src is not None and not _is_http_url(src):
            problems.append(f"{where}: source_url must be null or an http(s) URL")
        if src is None and (origin == "third_party" or (isinstance(lic, str) and lic.startswith("CC-BY"))):
            problems.append(f"{where}: source_url is required for third-party and CC BY tracks")
        mods = t["modifications"]
        if not isinstance(mods, list) or not all(isinstance(m, str) for m in mods):
            problems.append(f"{where}: modifications must be a list of strings")
        gen = t["generator"]
        if origin == "synthetic":
            if not isinstance(gen, dict):
                problems.append(f"{where}: synthetic tracks need the generator TrackSpec dict")
            else:
                try:
                    spec = synth.TrackSpec.from_dict(gen)
                except (TypeError, ValueError) as exc:
                    problems.append(f"{where}: invalid generator spec: {exc}")
                else:
                    if spec.sample_rate != sr:
                        problems.append(f"{where}: generator sample_rate {spec.sample_rate} != {sr}")
                    if n is not None and synth._ri(spec.duration_s * spec.sample_rate) != n:
                        problems.append(f"{where}: generator duration does not match num_samples")
        elif gen is not None:
            problems.append(f"{where}: generator must be null for non-synthetic tracks")
    return problems


def _manifest_path(catalog_dir: PathLike) -> Path:
    p = Path(catalog_dir)
    return p if p.name == MANIFEST and p.is_file() else p / MANIFEST


def load_manifest(catalog_dir: PathLike) -> dict:
    """Read and validate ``<dir>/manifest.json``; raises ValueError on any problem."""
    path = _manifest_path(catalog_dir)
    try:
        text = path.read_text(encoding="utf-8")
    except FileNotFoundError:
        raise ValueError(f"{path}: manifest not found") from None
    except UnicodeDecodeError as exc:
        raise ValueError(f"{path}: manifest is not valid UTF-8 ({exc})") from None
    try:
        manifest = json.loads(text)
    except json.JSONDecodeError as exc:
        raise ValueError(f"{path}: invalid JSON ({exc})") from None
    problems = validate_manifest(manifest)
    if problems:
        raise ValueError(f"{path}: invalid manifest: " + "; ".join(problems))
    return manifest


# --------------------------------------------------------------------------- generation


def profile_specs(profile: str = "full", n_tracks: Optional[int] = None, duration_s: Optional[float] = None,
                  base_seed: int = synth.DEFAULT_BASE_SEED) -> list:
    """Track specs for a catalog profile (with optional overrides)."""
    if profile not in PROFILES:
        raise ValueError(f"unknown profile {profile!r}; choose one of {sorted(PROFILES)}")
    default_n, (lo, hi), step = PROFILES[profile]
    n = default_n if n_tracks is None else n_tracks
    if not isinstance(n, int) or isinstance(n, bool) or not 1 <= n <= 10000:
        raise ValueError("n_tracks must be an integer in [1, 10000]")
    if duration_s is not None:
        if not isinstance(duration_s, (int, float)) or not 0.05 <= float(duration_s) <= synth.MAX_DURATION_S:
            raise ValueError(f"duration_s must be in [0.05, {synth.MAX_DURATION_S}] seconds")
        return synth.make_specs(n, durations=[float(duration_s)] * n, base_seed=base_seed,
                                sample_rate=CATALOG_SAMPLE_RATE)
    return synth.make_specs(n, base_seed=base_seed, sample_rate=CATALOG_SAMPLE_RATE,
                            duration_range=(lo, hi), duration_step=step)


def _synthetic_entry(index: int, spec: synth.TrackSpec, sha: str, n: int) -> dict:
    return {
        "id": spec.id,
        "index": index,
        "title": spec.title,
        "artist": SYNTH_ARTIST,
        "duration_s": n / spec.sample_rate,
        "num_samples": n,
        "pcm_bytes": 2 * n,
        "sha256_pcm": sha,
        "file": f"tracks/{spec.id}.wav",
        "origin": "synthetic",
        "license": "CC0-1.0",
        "license_url": ALLOWED_LICENSES["CC0-1.0"],
        "attribution": SYNTH_ATTRIBUTION,
        "source_url": None,
        "modifications": [],
        "generator": spec.to_dict(),
    }


def generate_catalog(out_dir: PathLike, profile: str = "full", n_tracks: Optional[int] = None,
                     duration_s: Optional[float] = None, base_seed: int = synth.DEFAULT_BASE_SEED,
                     progress: Optional[Callable] = None) -> dict:
    """Render a synthetic catalog into ``out_dir`` and return its manifest.

    Re-running with the same arguments reproduces identical files. A directory whose
    manifest lists imported (non-synthetic) tracks is never overwritten.
    ``progress(i, n, spec, seconds)`` is called after each track if given.
    """
    if not isinstance(base_seed, int) or isinstance(base_seed, bool) or not 0 <= base_seed < 2**63:
        raise ValueError("base_seed must be a non-negative integer")
    specs = profile_specs(profile, n_tracks, duration_s, base_seed)
    out = Path(out_dir)
    catalog_id = f"synthetic-{profile}-{base_seed}"
    if n_tracks is not None:
        catalog_id += f"-n{n_tracks}"
    if duration_s is not None:
        catalog_id += f"-d{float(duration_s):g}"
    with _catalog_lock(out):
        old_files = set()
        if (out / MANIFEST).exists():
            try:
                old = json.loads((out / MANIFEST).read_text(encoding="utf-8"))
                old_tracks = old["tracks"]
                if not isinstance(old_tracks, list) or not all(isinstance(t, dict) for t in old_tracks):
                    raise TypeError("tracks is not a list of objects")
            except (ValueError, KeyError, TypeError) as exc:
                raise ValueError(f"{out / MANIFEST} exists but is unreadable ({exc}); refusing to overwrite") from None
            if any(t.get("origin") != "synthetic" for t in old_tracks):
                raise ValueError(f"{out} contains imported tracks; refusing to overwrite it (use a new directory)")
            old_files = {t.get("file") for t in old_tracks if isinstance(t.get("file"), str)}
        (out / "tracks").mkdir(parents=True, exist_ok=True)
        entries = []
        for i, spec in enumerate(specs):
            t0 = time.perf_counter()
            samples = synth.render(spec)
            pcm = array_to_pcm16(samples)
            write_wav(out / "tracks" / f"{spec.id}.wav", pcm, spec.sample_rate)
            entries.append(_synthetic_entry(i, spec, sha256_hex(pcm), samples.size))
            if progress is not None:
                progress(i, len(specs), spec, time.perf_counter() - t0)
        manifest = {
            "schema_version": SCHEMA_VERSION,
            "catalog_id": catalog_id,
            "created_by": CREATED_BY,
            "sample_rate": CATALOG_SAMPLE_RATE,
            "channels": 1,
            "sample_width": 2,
            "generation": {"profile": profile, "base_seed": base_seed, "n_tracks": len(specs),
                           "duration_s": None if duration_s is None else float(duration_s)},
            "tracks": entries,
        }
        problems = validate_manifest(manifest)
        if problems:  # pragma: no cover - internal consistency check
            raise RuntimeError("generated manifest is invalid: " + "; ".join(problems))
        _write_manifest(out, manifest)
        for stale in sorted(old_files - {e["file"] for e in entries}):
            path = out / stale
            if stale.startswith("tracks/") and ".." not in stale and path.is_file():
                path.unlink()
    return manifest


# --------------------------------------------------------------------------- verification


def verify_catalog(catalog_dir: PathLike, rerender: bool = False) -> list:
    """Check a catalog; return a list of problems (empty list = OK).

    Recomputes ``sha256_pcm`` of every track. When a synthetic track's hash differs,
    the track is re-rendered from its ``generator`` spec and the maximum absolute
    sample difference is reported. ``rerender=True`` re-renders every synthetic
    track (reproducibility check on this platform).
    """
    root = Path(catalog_dir)
    try:
        manifest = load_manifest(root)
    except ValueError as exc:
        return [str(exc)]
    problems = []
    sr = manifest["sample_rate"]
    for t in manifest["tracks"]:
        tid = t["id"]
        path = root / t["file"]
        if not path.is_file():
            problems.append(f"{tid}: missing file {t['file']}")
            continue
        try:
            audio = read_wav_pcm16_mono(path, expected_rate=sr)
        except ValueError as exc:
            problems.append(f"{tid}: unreadable WAV: {exc}")
            continue
        if len(audio.pcm) != t["pcm_bytes"]:
            problems.append(f"{tid}: {len(audio.pcm)} PCM bytes in file, manifest says {t['pcm_bytes']}")
        digest = sha256_hex(audio.pcm)
        mismatch = digest != t["sha256_pcm"]
        if t["origin"] == "synthetic" and (mismatch or rerender):
            try:
                fresh = synth.render(synth.TrackSpec.from_dict(t["generator"]))
            except ValueError as exc:
                problems.append(f"{tid}: cannot re-render generator spec: {exc}")
                continue
            fresh_sha = sha256_hex(array_to_pcm16(fresh))
            if mismatch:
                file_samples = pcm16_to_array(audio.pcm).astype(np.int32)
                if file_samples.size == fresh.size:
                    diff = np.abs(file_samples - fresh.astype(np.int32))
                    detail = f"max abs sample difference vs fresh render = {int(diff.max())} ({int(np.count_nonzero(diff))} samples differ)"
                else:
                    detail = f"file has {file_samples.size} samples, fresh render has {fresh.size}"
                agree = "matches" if fresh_sha == t["sha256_pcm"] else "does NOT match"
                problems.append(f"{tid}: sha256_pcm mismatch (file {digest[:16]}..., manifest {t['sha256_pcm'][:16]}...); "
                                f"{detail}; fresh render {agree} the manifest hash")
            elif fresh_sha != t["sha256_pcm"]:
                diff = np.abs(pcm16_to_array(audio.pcm).astype(np.int32) - fresh.astype(np.int32)) \
                    if fresh.size == len(audio.pcm) // 2 else None
                extra = f"; max abs sample difference = {int(diff.max())}" if diff is not None else ""
                problems.append(f"{tid}: re-render on this platform differs from the stored audio{extra}")
        elif mismatch:
            problems.append(f"{tid}: sha256_pcm mismatch (file {digest[:16]}..., manifest {t['sha256_pcm'][:16]}...)")
    listed = {t["file"] for t in manifest["tracks"]}
    tracks_dir = root / "tracks"
    if tracks_dir.is_dir():
        for p in sorted(tracks_dir.iterdir()):
            rel = f"tracks/{p.name}"
            if rel not in listed and not p.name.startswith("."):
                problems.append(f"unlisted file in catalog: {rel}")
    others = [t for t in manifest["tracks"] if t["origin"] != "synthetic"]
    if others:
        att = root / ATTRIBUTION
        if not att.is_file():
            problems.append(f"{ATTRIBUTION} missing although the catalog has non-synthetic tracks")
        else:
            text = att.read_text(encoding="utf-8")
            for t in others:
                if f"`{t['id']}`" not in text:
                    problems.append(f"{ATTRIBUTION} does not list track {t['id']}")
    return problems


